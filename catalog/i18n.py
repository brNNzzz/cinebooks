"""
Sistema simples de troca de idioma do site.

Não usamos o sistema de tradução "de fábrica" do Django (gettext/.po/.mo)
porque ele depende de um programa externo (o "gettext") pra compilar os
arquivos de tradução — nem sempre instalado no computador de quem for rodar
o projeto, e isso quebraria o `python manage.py runserver` de quem não tiver
ele. Em vez disso, guardamos as traduções aqui mesmo, num dicionário Python
comum: funciona em qualquer computador, sem instalar nada a mais.

Como funciona:
- IDIOMAS: lista de idiomas disponíveis (código, nome e bandeira).
- TRADUCOES: para cada idioma, um dicionário {"chave": "texto traduzido"}.
- A tag de template `{% t "chave" %}` (em catalog/templatetags/i18n_custom.py)
  busca o texto certo de acordo com o idioma escolhido pela pessoa (guardado
  na sessão dela).
- Cobrimos os textos fixos da interface (menu, botões, rótulos). Além disso,
  quando alguém busca um filme/série que AINDA NÃO está no catálogo, a busca
  já pede os dados pro TMDB no idioma selecionado (veja o parâmetro `idioma`
  em catalog/busca_externa.py) — então título, sinopse e gêneros desse título
  novo já chegam traduzidos. Livros (Open Library) e títulos que já estavam
  no catálogo continuam no idioma em que foram cadastrados originalmente,
  porque re-traduzir tudo em toda visita deixaria o site lento.
"""

